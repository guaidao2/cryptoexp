def gen_rsa_direct(results, params):
    n, e, c = params["n"], params["e"], params["c"]
    lines = [_HEAD, "# === RSA: private key material known -> decrypt directly ===", _INT_TO_BYTES]
    if params.get("p") and params.get("q"):
        lines.append(f"n = {n}\ne = {e}\nc = {c}\np = {params['p']}\nq = {params['q']}")
        body = '''
phi = (p - 1) * (q - 1)
d = pow(e, -1, phi)
m = pow(c, d, n)
print("[+] flag:", itob(m))
'''
    elif params.get("d"):
        lines.append(f"n = {n}\ne = {e}\nc = {c}\nd = {params['d']}")
        body = '''
m = pow(c, d, n)
print("[+] flag:", itob(m))
'''
    else:
        phi_in = params.get("phi") or params.get("phi_n")
        lines.append(f"n = {n}\ne = {e}\nc = {c}\nphi = {phi_in}")
        body = '''
import math

# recover p and q from phi: p+q = n - phi + 1, solve the quadratic
s = n - phi + 1
disc = s * s - 4 * n
r = math.isqrt(disc)          # integer sqrt: disc**0.5 overflows on real keys
assert r * r == disc, "wrong phi: discriminant is not a perfect square"
p = (s + r) // 2
q = (s - r) // 2
assert p * q == n, "factorization check failed"
d = pow(e, -1, (p - 1) * (q - 1))
print("[+] flag:", itob(pow(c, d, n)))
'''
    lines.append(body)
    return "\n".join(lines)


