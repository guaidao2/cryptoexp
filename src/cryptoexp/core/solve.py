_IROOT_FN = '''
def iroot(n, k):
    """Integer k-th root (Newton iteration), returns (root, exact)"""
    if n < 0:
        raise ValueError("negative")
    if n in (0, 1) or k == 1:
        return n, True
    x = 1 << ((n.bit_length() + k - 1) // k)
    while True:
        y = ((k - 1) * x + n // (x ** (k - 1))) // k
        if y >= x:
            break
        x = y
    while x ** k > n:
        x -= 1
    while (x + 1) ** k <= n:
        x += 1
    return x, x ** k == n
'''

_INT_TO_BYTES = '''
def itob(x):
    return x.to_bytes((x.bit_length() + 7) // 8, 'big') if x else b''
'''


def _reporoot() -> str:
    """Directory to put on sys.path so `import cryptoexp` works inside a script

    src layout: this file is `<root>/src/cryptoexp/core/solve.py`, so the importable
    root is the parent of the *package* directory (`.../src`). It used to return the
    package directory itself, and every generated script that imported the library
    died with ModuleNotFoundError: No module named 'cryptoexp'.
    """
    package_dir = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    return os.path.dirname(package_dir)


def _params(results):
    """Parameter extraction always goes through the analysis layer's collect_params
    (one implementation, so analysis and generation cannot drift apart)"""
    from .analysis.rsa import collect_params
    ctx = results.get("_ctx") or {}
    rsa = (results.get("rsa") or {}).get("params") or {}
    raw = collect_params(ctx)
    p = {}
    p["n"] = raw.get("n")
    p["e"] = raw.get("e")
    p["c"] = raw.get("c")
    p["n_list"] = raw.get("n_list") or []
    p["c_list"] = raw.get("c_list") or []
    for key in ("p", "q", "dp", "d", "phi"):
        if raw.get(key):
            p[key] = raw[key]
    p["params_meta"] = rsa
    blobs = (results.get("encoding") or {}).get("blobs") or []
    p["blobs"] = blobs
    p["candidates"] = {
        "encoding": (results.get("encoding") or {}).get("candidates", []),
        "classical": (results.get("classical") or {}).get("candidates", []),
    }
    p["lcg"] = (results.get("numbertheory") or {}).get("lcg")
    p["knapsack"] = (results.get("lattice") or {}).get("knapsack")
    p["coppersmith"] = (results.get("lattice") or {}).get("coppersmith")
    p["symmetric"] = results.get("symmetric") or {}
    p["crc"] = results.get("crc") or {}
    p["lfsr"] = results.get("lfsr") or {}
    crc_params = (p["crc"].get("params") or {})
    p["crc_prefix"] = crc_params.get("prefix", b"")
    p["crc_suffix"] = crc_params.get("suffix", b"")
    p["crc_target"] = crc_params.get("target", 0)
    p["crc_unknown_len"] = crc_params.get("unknown_len", 0)
    p["raw_text"] = ctx.get("raw_text", "")
    return p


def _bubble_comment(text: str) -> str:
    return "\n".join(f"# {line}" if line.strip() else "#" for line in text.splitlines())


def _blob_text(blob: dict) -> str:
    """Ciphertext for generated scripts: never the display-truncated variant"""
    return blob.get("full_text") or blob.get("text", "")


def _hex_ciphertext(blob: dict) -> bool:
    """XOR templates require real hex ciphertext.

    A Caesar/Vigenere text is not hex, and routing it to an XOR template produced a
    script that crashed in bytes.fromhex() (caught by the generated-script test).
    """
    text = _blob_text(blob)
    return _E.from_hex(text) is not None and len(text.strip()) >= 8


