def gen_rsa_shared_prime(results, params):
    ns = [v for v in dict.fromkeys(params["n_list"] or [params["n"]]) if v]
    cs = params["c_list"]
    e = params["e"]
    return "\n".join([_HEAD, "# === RSA: shared factor across moduli -> gcd factorization ===", _INT_TO_BYTES,
                      "import math",
                      f"ns = {ns}\ncs = {cs}\ne = {e}",
                      '''
for i in range(len(ns)):
    for j in range(i + 1, len(ns)):
        g = math.gcd(ns[i], ns[j])
        if 1 < g < min(ns[i], ns[j]):
            for n in (ns[i], ns[j]):
                p = math.gcd(n, g)
                if 1 < p < n:
                    q = n // p
                    phi = (p - 1) * (q - 1)
                    d = pow(e, -1, phi)
                    for c in cs:
                        if c < n:
                            m = pow(c, d, n)
                            print("[+] flag:", itob(m))
'''])


def gen_rsa_broadcast(results, params):
    e = params["e"]
    ns = [v for v in dict.fromkeys(params["n_list"]) if v]
    cs = params["c_list"]
    return "\n".join([_HEAD, "# === RSA: low-exponent broadcast (Håstad) -> CRT + root ===", _IROOT_FN,
                      _INT_TO_BYTES, "from math import gcd",
                      f"e = {e}\nns = {ns[:e] if e else ns}\ncs = {cs[:e] if e else cs}",
                      '''
def crt(pairs):
    x, M = 0, 1
    for a, m in pairs:
        g = gcd(M, m)
        assert g == 1, "moduli are not coprime, use the shared-factor template"
        inv = pow(M % m, -1, m)
        t = ((a - x) % m) * inv % m
        x, M = (x + M * t) % (M * m), M * m
    return x % M, M

C, M = crt(list(zip(cs, ns)))
root, exact = iroot(C, e)
assert exact, "still not a perfect e-th power after CRT (plaintext may be padded)"
print("[+] flag:", itob(root))
'''])


def gen_rsa_wiener(results, params):
    n, e, c = params["n"], params["e"], params["c"]
    return "\n".join([_HEAD, "# === RSA: Wiener attack (d too small) -> continued fraction convergents ===",
                      _INT_TO_BYTES, "import math",
                      f"n = {n}\ne = {e}\nc = {c}",
                      '''
def cf(a, b):
    out = []
    while b:
        out.append(a // b)
        a, b = b, a % b
    return out

def convergents(seq):
    h0, h1, k0, k1 = 1, seq[0], 0, 1
    yield h1, k1
    for a in seq[1:]:
        h0, h1 = h1, a * h1 + h0
        k0, k1 = k1, a * k1 + k0
        yield h1, k1

for k, d in convergents(cf(e, n)):
    if k == 0:
        continue
    if (e * d - 1) % k:
        continue
    phi = (e * d - 1) // k
    s = n - phi + 1
    disc = s * s - 4 * n
    if disc < 0:
        continue
    r = math.isqrt(disc)          # integer sqrt: disc**0.5 overflows on real keys
    if r * r != disc or (s + r) % 2:
        continue
    p, q = (s + r) // 2, (s - r) // 2
    if p * q == n:
        print("[+] Wiener recovered d =", d)
        print("[+] flag:", itob(pow(c, d, n)))
        break
'''])


def gen_rsa_fermat(results, params):
    n, e, c = params["n"], params["e"], params["c"]
    return "\n".join([_HEAD, "# === RSA: Fermat factorization (p and q close) ===", _INT_TO_BYTES,
                      f"n = {n}\ne = {e}\nc = {c}",
                      '''
import math

a = math.isqrt(n)             # integer sqrt: n**0.5 overflows on real keys
if a * a < n:
    a += 1
for _ in range(2000000):
    b2 = a * a - n
    b = math.isqrt(b2)
    if b * b == b2:
        p, q = a - b, a + b
        assert p * q == n
        d = pow(e, -1, (p - 1) * (q - 1))
        print("[+] flag:", itob(pow(c, d, n)))
        break
    a += 1
else:
    print("[-] no factorization within 2,000,000 rounds (p and q are not close enough)")
'''])


def gen_rsa_factor(results, params):
    n, e, c = params["n"], params["e"], params["c"]
    return "\n".join([_HEAD, "# === RSA: direct factorization (Pollard rho) -- for modest n bit sizes ===",
                      _INT_TO_BYTES, "import math, random",
                      f"n = {n}\ne = {e}\nc = {c}",
                      '''
def rho(n):
    if n % 2 == 0:
        return 2
    while True:
        x = y = random.randrange(2, n)
        cst = random.randrange(1, n)
        d = 1
        while d == 1:
            x = (x * x + cst) % n
            y = (y * y + cst) % n
            y = (y * y + cst) % n
            d = math.gcd(abs(x - y), n)
        if d != n:
            return d

p = rho(n)
q = n // p
assert p * q == n
d = pow(e, -1, (p - 1) * (q - 1))
print("[+] p =", p)
print("[+] flag:", itob(pow(c, d, n)))
'''])


