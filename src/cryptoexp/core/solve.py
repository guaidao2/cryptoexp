"""Solve script generation — template registry + priority routing.
The counterpart of intelpwn's exploit generator.

Two hard rules (inherited from intelpwn: "never emit a script that is bound to crash"):
  1. A generated script uses **only the standard library at its core**, so
     `python3 solve_xxx.py` just runs; when long code such as LLL/Coppersmith is
     needed, the script explicitly imports this repo's utilities and states the
     preconditions in a comment.
  2. When there is no working route, be honest and emit a `[skeleton]`: write down
     the attack idea, the oracle it needs and where the gap is — never pretend it works.
"""

import os

from ..utils import encoding as _E

_SOLVERS = []
_BUILTINS_LOADED = False


def register_solver(name, predicate, gen_fn, priority=500, meta=None):
    """Register a solve template

    predicate(results) -> bool          applicability test
    gen_fn(results, params) -> str      returns the complete script
    priority: lower runs first (built-ins 10-90, plugins default 500, skeleton 999)
    """
    if not callable(predicate) or not callable(gen_fn):
        raise ValueError("predicate/gen_fn must be callables")
    _SOLVERS.append({"name": name, "predicate": predicate, "gen": gen_fn,
                     "priority": priority, "meta": meta or {}})
    _SOLVERS.sort(key=lambda s: s["priority"])


def list_solvers():
    return [(s["name"], s["priority"]) for s in _SOLVERS]


