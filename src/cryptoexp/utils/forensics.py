def _lcg_replay(params, outputs):
    """True when x_{i+1} = a*x_i + c (mod m) reproduces the whole observation"""
    a, c, m = params["a"], params["c"], params["m"]
    if m <= 1:
        return False
    state = int(outputs[0]) % m
    for observed in outputs[1:]:
        state = (a * state + c) % m
        if state != int(observed) % m:
            return False
    return True


def _glibc_words_ok(rec, outputs):
    """Check a recovered TYPE_3 window against the observations it claims to explain

    The lower layer returns `words`, one 32-bit state word per observation, with
    `rand()` having printed `word >> 1`. Two things are therefore checkable without
    any held-out data: every word reproduces its observation, and the window follows
    the generator's own recurrence `w_j = w_{j-31} + w_{j-3} (mod 2^32)`. That is a
    consistency proof, not a prediction proof, which is why `_glibc_attempt` prefers a
    held-out tail whenever one is available and only falls back to this check.
    """
    words = [int(w) & _MASK32 for w in rec.get("words", [])]
    if len(words) < len(outputs):
        return False
    for pos, observed in enumerate(outputs):
        if (words[pos] >> 1) != (int(observed) & 0x7fffffff):
            return False
    for pos in range(31, len(outputs)):
        if words[pos] != (words[pos - 31] + words[pos - 3]) & _MASK32:
            return False
    return True


def _glibc_attempt(outputs):
    """Recover the glibc TYPE_3 state -> a hit dict, or None when it cannot be pinned

    Recovery only counts when it can be *checked forwards*. That is why a tail of the
    observation is held out whenever there is one: the state is recovered from the
    prefix and its prediction must then reproduce the values it never saw, exactly as
    with MT19937. Only when there is no tail to hold out (the caller supplied barely
    enough outputs) does a self-consistency check stand in, and that hit is reported
    with "medium" confidence rather than sold as verified.

    A prefix whose state fits but whose prediction diverges on the tail is discarded
    instead of being returned, because that is precisely the shape of the silent wrong
    answer this module exists to avoid.
    """
    n = len(outputs)
    prefixes = []
    if n > 40:
        for hold in (min(32, n - 40), n - 40, 8, 4):
            if 35 <= n - hold < n:
                prefixes.append(n - hold)
    prefixes.append(n)
    seen = set()
    for prefix in prefixes:
        if prefix in seen:
            continue
        seen.add(prefix)
        try:
            rec = PE.glibc_rand_recover(outputs[:prefix])
        except Exception:                              # pragma: no cover - defensive
            continue
        if rec is None:
            continue
        if prefix < n:
            predicted = PE.glibc_rand_predict(outputs[:prefix], n - prefix)
            tail = [int(o) & 0x7fffffff for o in outputs[prefix:]]
            if predicted == tail:
                return {
                    "family": "glibc_rand",
                    "confidence": "high",
                    "state": {"state": rec["state"], "index": rec["index"]},
                    "predict": PE.glibc_rand_predict(outputs, 4),
                    "detail": ("TYPE_3 additive generator recovered from the first %d "
                               "outputs and verified against the %d held-out values "
                               "that follow (they match exactly); %d state candidates "
                               "were consistent"
                               % (prefix, n - prefix,
                                  rec.get("solutions_considered", 0))),
                }
            continue
        if _glibc_words_ok(rec, outputs):
            return {
                "family": "glibc_rand",
                "confidence": "medium",
                "state": {"state": rec["state"], "index": rec["index"]},
                "predict": PE.glibc_rand_predict(outputs, 4),
                "detail": ("TYPE_3 additive generator fitted to all %d outputs and "
                           "internally consistent (every word reproduces its output "
                           "and the recurrence holds); no held-out value was available "
                           "to confirm the prediction, so capture more to upgrade this "
                           "to high confidence" % n),
            }
    return None


def _xorshift_replay(state, outputs):
    """`state` is the value that produced outputs[0]; state == output for xorshift32"""
    value = int(state) & _MASK32
    for observed in outputs:
        if value != (int(observed) & _MASK32):
            return False
        value = PE.xorshift32_next(value)
    return True


def _java_replay(seed, outputs):
    """`seed` is the internal 48-bit state; replay `next(32)` against the observations"""
    state = int(seed) & _MASK48
    for observed in outputs:
        state = (state * _JAVA_MAGIC + _JAVA_ADDEND) & _MASK48
        value = state >> 16
        if value >= 0x80000000:
            value -= 0x100000000
        if value != int(observed):
            return False
    return True


def _prng_candidates(outputs, deep, tried, only=None):
    """Run each family's recovery in cost order, appending to `tried`; return the hits

    Cost order is deliberate: glibc (one propagation, no search), then xorshift32 (a
    closed-form inversion), then Java Random (a 2^16 sweep), then a generic LCG
    (arithmetic on the difference sequence), and finally MT19937 (624 untemper steps,
    which only makes sense once the cheap explanations are gone). `only` restricts the
    run to a single family name - that is how the screening loop in `detect_weak_prng`
    stops paying for the expensive families as soon as a cheap one explains the data.

    Every hit is checked forwards before it is returned, through the family's own
    verification helper: glibc and MT19937 hold out a tail of the observation and
    require the recovered state to predict it, xorshift32/Java/LCG re-derive every
    supplied value from the recovered parameters. The lower layers verify internally
    too, but repeating it here means one rule governs all five families, so a change
    in a lower layer cannot turn a failed recovery into a confident claim.
    """
    hits = []
    n = len(outputs)

    def want(family):
        return only is None or only == family

    if want("glibc_rand"):
        if n >= 35 and all(0 <= v < (1 << 31) for v in outputs):
            hit = _glibc_attempt(outputs)
            if hit is None:
                tried.append({"family": "glibc_rand", "ok": False,
                              "note": ("no single state is determined by these %d "
                                       "outputs (the bit rand() discards stays "
                                       "ambiguous); capture more - about 100 were "
                                       "needed in testing" % n)})
            else:
                hits.append(hit)
                tried.append({"family": "glibc_rand", "ok": True,
                              "note": hit["detail"]})
        elif n >= 35:
            tried.append({"family": "glibc_rand", "ok": False,
                          "note": "outputs reach 2^31 or beyond, which rand() (31 "
                                  "bits) cannot produce"})
        else:
            tried.append({"family": "glibc_rand", "ok": False,
                          "note": "needs >= 35 outputs to pin the 31-word state down "
                                  "(have %d)" % n})
        if hits and not deep:
            return hits

    if want("xorshift32"):
        if all(0 <= v <= _MASK32 for v in outputs):
            try:
                rec = PE.xorshift_recover(outputs)
            except Exception as exc:                   # pragma: no cover - defensive
                rec, why = None, "raised %s" % exc
            else:
                why = "no non-zero state reproduces the whole observation"
            if rec and _xorshift_replay(rec["state"], outputs):
                hits.append({
                    "family": "xorshift32",
                    "confidence": "high",
                    "state": {"state": rec["state"]},
                    "predict": PE.xorshift_predict(outputs, 4),
                    "detail": ("xorshift32 (13,17,5) state inverted out of outputs[1] "
                               "and replayed over %d observed values" % n),
                })
                tried.append({"family": "xorshift32", "ok": True,
                              "note": "state recovered and replayed"})
            else:
                tried.append({"family": "xorshift32", "ok": False, "note": why})
        else:
            tried.append({"family": "xorshift32", "ok": False,
                          "note": "outputs exceed 32 bits, which xorshift32 cannot "
                                  "produce"})
        if hits and not deep:
            return hits

    if want("java_random"):
        if all(-(1 << 31) <= v < (1 << 31) for v in outputs) and n >= 3:
            try:
                rec = PE.java_random_recover(outputs)
            except Exception as exc:                   # pragma: no cover - defensive
                rec, why = None, "raised %s" % exc
            else:
                why = "no 48-bit state in range reproduces the whole observation"
            if rec and _java_replay(rec["seed"], outputs):
                hits.append({
                    "family": "java_random",
                    "confidence": "high",
                    "state": {"seed": rec["seed"]},
                    "predict": PE.java_random_predict(outputs, 4),
                    "detail": ("java.util.Random (48-bit LCG, nextInt) internal state "
                               "recovered from the printed high bits and replayed over "
                               "%d observed values" % n),
                })
                tried.append({"family": "java_random", "ok": True,
                              "note": "internal state recovered and replayed"})
            else:
                tried.append({"family": "java_random", "ok": False, "note": why})
        else:
            tried.append({"family": "java_random", "ok": False,
                          "note": "needs signed 32-bit `nextInt()` values"})
        if hits and not deep:
            return hits

    if want("lcg"):
        if n >= 4:
            try:
                rec = A.lcg_recover(outputs)
            except Exception as exc:                   # pragma: no cover - defensive
                rec, why = None, "raised %s" % exc
            else:
                why = "no (a, c, m) reproduces the whole observation"
            if rec and _lcg_replay(rec, outputs):
                nxt = int(outputs[-1])
                pred = []
                for _ in range(4):
                    nxt = (rec["a"] * nxt + rec["c"]) % rec["m"]
                    pred.append(nxt)
                hits.append({
                    "family": "lcg",
                    "confidence": "high",
                    "state": {"a": rec["a"], "c": rec["c"], "m": rec["m"]},
                    "predict": pred,
                    "detail": ("linear congruential generator replayed over %d observed "
                               "values: x_next = (a*x + c) mod m with a = %d, c = %d, "
                               "m = %d" % (n, rec["a"], rec["c"], rec["m"])),
                })
                tried.append({"family": "lcg", "ok": True,
                              "note": "parameters recovered and replayed"})
            else:
                tried.append({"family": "lcg", "ok": False, "note": why})
        else:
            tried.append({"family": "lcg", "ok": False,
                          "note": "needs >= 4 consecutive outputs to fit a, c, m"})
        if hits and not deep:
            return hits

    if want("mt19937"):
        if n >= _MT_MIN_WORDS and all(0 <= v <= _MASK32 for v in outputs):
            # `clone_from_outputs` untempers the 624 words and leaves the clone
            # standing *right after them* (index == N), so its next call twists the
            # recovered block and yields observation 625 onwards. Two consequences,
            # both of which an earlier version got wrong: the held-out tail of the
            # observation is the evidence (replaying the 624 input words through the
            # clone rejected every genuine MT19937 stream), and the clone must then be
            # advanced through the rest of the observation before `predict` - otherwise
            # the reported "next 4" are four values the caller already gave us.
            try:
                probe = PR.clone_from_outputs(outputs[:_MT_MIN_WORDS])
            except Exception as exc:                   # pragma: no cover - defensive
                probe, why = None, "raised %s" % exc
            else:
                why = "the cloned state does not replay the held-out observations"
            if probe is not None:
                tail_ok = True
                for observed in outputs[_MT_MIN_WORDS:]:
                    if probe.next32() != (int(observed) & _MASK32):
                        tail_ok = False
                        break
                verified = n > _MT_MIN_WORDS
                if tail_ok:
                    live = PR.clone_from_outputs(outputs[:_MT_MIN_WORDS])
                    for _ in range(n - _MT_MIN_WORDS):
                        live.next32()
                    pred = [live.next32() for _ in range(4)]
                    if verified:
                        detail = ("MT19937 state untempered from the first %d words and "
                                  "verified against the %d held-out values that follow "
                                  "(they match exactly); `state.clone` is a PR.MT19937 "
                                  "standing after the observation and predicts the whole "
                                  "future stream" % (_MT_MIN_WORDS, n - _MT_MIN_WORDS))
                        confidence = "high"
                    else:
                        detail = ("MT19937 state untempered from exactly %d words: the "
                                  "clone reproduces the stream by construction, but no "
                                  "held-out value could confirm it, so this is self-"
                                  "consistent rather than verified - capture one more "
                                  "word to make it a high-confidence claim"
                                  % _MT_MIN_WORDS)
                        confidence = "medium"
                    hits.append({
                        "family": "mt19937",
                        "confidence": confidence,
                        "state": {"clone": live},
                        "predict": pred,
                        "detail": detail,
                    })
                    tried.append({"family": "mt19937", "ok": True,
                                  "note": detail})
                else:
                    tried.append({"family": "mt19937", "ok": False, "note": why})
        elif n >= _MT_MIN_WORDS:
            tried.append({"family": "mt19937", "ok": False,
                          "note": "outputs exceed 32 bits, which getrandbits(32) cannot "
                                  "produce"})
        else:
            tried.append({"family": "mt19937", "ok": False,
                          "note": "needs >= %d 32-bit words, only %d observed"
                                  % (_MT_MIN_WORDS, n)})

    return hits

def detect_weak_prng(outputs, effort="normal"):
    """Fingerprint the generator behind an observed "random" output sequence

    Why a tester needs it: session tokens, password-reset nonces, API keys,
    invitation codes and "unpredictable" object IDs are the highest-value material
    an engagement collects, and their security rests entirely on the generator. A
    sequence of a few dozen observed values is often enough to name the generator
    and then predict every future value - "the tokens look random" becomes "the
    tokens are an LCG, here are the next four" without touching the target again.
    This function runs the recoveries in escalating cost order and claims a family
    only when that family's recovery *replays every observed value*; a sequence it
    cannot reproduce gets family=None, because a wrong family name in a report is
    worse than "unidentified".

    Order and what each family is:
        glibc rand()  additive lagged Fibonacci (TYPE_3), >= 35 values
        xorshift32    Marsaglia (13,17,5), state == output
        java.util.Random  48-bit LCG whose high 32 bits are printed
        generic LCG   x_next = (a*x + c) mod m, modulus estimated when unknown
        MT19937       >= 624 32-bit words, state untempered from the observations

    Args:
        outputs: the observed integers, oldest first. Bytes/str entries are
            converted to ints (big-endian / digit string). Negative values are kept
            (Java `nextInt()` prints them).
        effort: "quick" | "normal" | "deep" ("fast" is accepted as a synonym of
            "quick"). After the first verified family wins, quick and normal stop;
            deep keeps going so that the `tried` list covers every family - useful
            when the goal is to rule generators out as well as in.

    Returns:
        {
          "family": str or None ("glibc_rand", "xorshift32", "java_random", "lcg",
                    "mt19937"),
          "confidence": "high" | "medium" | "low" | None. "high" means the recovery
                    was checked *forwards*: state recovered from part of the
                    observation, prediction matched the values it never saw. "medium"
                    means the state reproduces everything supplied but there was no
                    held-out value to confirm it (exactly 624 MT19937 words, or barely
                    enough glibc outputs), "low" is reserved for a structurally
                    possible but unverified fit, and None accompanies family None.
          "state": the recovered state (dict; for MT19937 it holds the PR.MT19937
                    clone itself),
          "predict": [next 4 values] or None,
          "detail": str - what was verified, or why nothing was claimed,
          "weak_prng": bool - the convenience verdict for a report line,
          "tried": [{"family", "ok", "note"}, ...] - every attempt, including the
                    ones that could not run because there were too few outputs.
        }
    """
    if isinstance(outputs, (bytes, bytearray, str)):
        raise ValueError("outputs must be a sequence of ints, not a single blob")
    values = []
    for item in outputs:
        if isinstance(item, (bytes, bytearray)):
            values.append(R.bytes_to_long(item))
        else:
            values.append(int(item))

    tier = {"fast": "quick", "quick": "quick", "normal": "normal", "deep": "deep"}
    if effort not in tier:
        raise ValueError("effort must be 'quick', 'normal' or 'deep'")
    deep = tier[effort] == "deep"

    result = {"family": None, "confidence": None, "state": None, "predict": None,
              "detail": "", "weak_prng": False, "tried": []}
    if not values:
        result["detail"] = "no outputs given: nothing to fingerprint"
        return result
    if len(values) < 3:
        result["detail"] = ("only %d output(s): every recovery here needs at least 3, "
                            "so no family was tested to a conclusion" % len(values))
        return result

    if not deep:
        # Screening order is a cost order (see `_prng_candidates`): cheap,
        # structurally narrow families first. A verified hit short-circuits, so the
        # common case pays for one or two recoveries rather than all five.
        tried = []
        hits = []
        for family in ("glibc_rand", "xorshift32", "java_random", "lcg", "mt19937"):
            hits = _prng_candidates(values, deep=False, tried=tried, only=family)
            if hits:
                break
    else:
        tried = []
        hits = _prng_candidates(values, deep=True, tried=tried)

    result["tried"] = tried
    if not hits:
        result["detail"] = ("no tested family reproduces the observed sequence "
                            "(%d value(s)); see `tried` for what was ruled out"
                            % len(values))
        return result

    best = hits[0]
    result["family"] = best["family"]
    result["confidence"] = best["confidence"]
    result["state"] = best["state"]
    result["predict"] = best["predict"]
    result["detail"] = best["detail"]
    result["weak_prng"] = best["confidence"] == "high"
    if len(hits) > 1:
        result["detail"] += ("; %d family/families reproduce this data, the "
                             "highest-priority one is reported"
                             % len(hits))
        result["ambiguous"] = [h["family"] for h in hits]
    return result
