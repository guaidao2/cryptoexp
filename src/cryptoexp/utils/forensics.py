"""Forensics for real deployments - key audits, captured tokens and wire material

This is the layer a penetration tester or a security researcher points at material
that came *out of the world* rather than out of a challenge file: a dump of a
TLS/SSH/embedded fleet's RSA moduli, a DER-encoded ECDSA signature lifted from
X.509 or from captured protocol traffic, a JWS/JWT pasted from a bug bounty
target, a stream of "random" session tokens. Every function here answers one
question that ends up in a report - "which hosts share a prime?", "is that
signature worth an offline nonce-reuse attempt?", "does this service accept
alg=none?", "is this key reachable by an attack we can actually run?", "are those
tokens generated by a linear congruential generator?" - and none of them prints,
mutates global state, or raises on an ordinary negative answer.

Conventions used throughout:

    * explicit parameters, plain dicts/lists/tuples out;
    * "I looked and found nothing" is a normal result (empty list, ok=False, or a
      note), never an exception;
    * "this input is not what you say it is" is a ValueError;
    * no check is ever skipped silently - the audit's `checked` field and the
      fingerprint's `tried` field record every check and why it did not run.

Everything is hand-rolled on the standard library and reuses the lower layers
(`algebra`, `modular`, `rsa_ops`, `keys`, `prng`, `prng_extra`) rather than
duplicating them.
"""

