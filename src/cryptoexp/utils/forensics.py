def parse_der_signature(der):
    """Parse SEQUENCE { INTEGER r, INTEGER s } -> {"r": int, "s": int}, else None

    Why a tester needs it: an ECDSA/DSA signature lifted out of an X.509 certificate,
    a JWS field, a TLS handshake or a captured proprietary protocol arrives as raw DER.
    The signature itself is worthless to the analyst - what matters is feeding r and s
    into the nonce-reuse and lattice attacks (`signatures.ecdsa_nonce_reuse`, ...).
    Doing that by hand for every captured blob is where mistakes happen, and the two
    classic parsing traps both live in the INTEGERs: the 0x00 prefix that keeps a
    high-bit value positive, and the long-form length that appears as soon as r is 128
    bytes. Both are handled here.

    The DER TLV reading is delegated to `keys._der_read` / `keys._der_decode_int`, so
    the package has exactly one DER parser rather than two that can drift apart; that
    layer already handles short/long-form lengths, rejects the indefinite form, strips
    the leading 0x00 of a positive INTEGER and refuses a negative one.

    Trailing bytes after the SEQUENCE are rejected: a blob followed by garbage is not a
    bare signature, and silently ignoring the tail is how a parser ends up reporting
    the r/s of some enclosing structure.

    Args:
        der: bytes (or bytearray) of the DER blob.

    Returns:
        {"r": int, "s": int} on a clean parse; None when the structure is not
        SEQUENCE{r, s}. None means "not a bare DER signature", an ordinary answer for
        TLS record bytes or a PEM file that was pasted by mistake. Only a non-bytes
        argument raises.

    Note the shape: PKCS#1 RSAPublicKey is also SEQUENCE{INTEGER, INTEGER}, so a
    two-integer blob is accepted whatever its provenance - this parser reads
    structure, and telling a signature from a public key needs context it does not
    have.
    """
    if isinstance(der, (bytearray, memoryview)):
        der = bytes(der)
    if not isinstance(der, bytes):
        raise ValueError("parse_der_signature expects bytes")
    if not der:
        return None
    try:
        tag, body, end = K._der_read(der, 0)
        if tag != 0x30 or end != len(der):
            return None
        tag_r, raw_r, off = K._der_read(body, 0)
        if tag_r != 0x02:
            return None
        tag_s, raw_s, off = K._der_read(body, off)
        if tag_s != 0x02 or off != len(body):
            return None
        r = K._der_decode_int(raw_r)
        s = K._der_decode_int(raw_s)
    except ValueError:
        return None
    if r <= 0 or s <= 0:
        return None
    return {"r": r, "s": s}

# ------------------------------------------------------------------ JWT / JWS

def _b64url_decode(segment):
    """base64url segment -> bytes, tolerant of missing padding and of -/_"""
    if isinstance(segment, (bytes, bytearray)):
        segment = bytes(segment).decode("ascii", "ignore")
    text = str(segment).strip()
    if not text:
        raise ValueError("empty base64url segment")
    if any(ch not in _B64URL_CHARS for ch in text):
        raise ValueError("segment contains characters outside the base64url alphabet")
    cleaned = text.replace("-", "+").replace("_", "/")
    cleaned += "=" * ((-len(cleaned)) % 4)
    return base64.b64decode(cleaned)


def parse_jwt(token):
    """Split and decode a JWS/JWT - and report the algorithm it *claims* to use

    Why a tester needs it: pasting a bearer token into an engagement note and
    reading its claims (iss, sub, exp, scope, roles) is the fastest way to learn
    what a target trusts. Two findings fall straight out of the header and belong
    in the report: `alg: none` (an unsigned token some stacks still accept) and a
    symmetric algorithm such as HS256, where a gateway that also hands out a public
    key is a signature-forgery finding waiting to happen.

    The signature is deliberately NOT verified. Verification is a policy decision -
    which key, which clock skew, which `alg` list is allowed - and this library's
    job is to hand back the decoded material plus `hmac_sha256` for the caller that
    knows its policy. A function that returned True/False here would be answering a
    question it cannot know the parameters of.

    Args:
        token: str (or ASCII/UTF-8 bytes) of the compact serialisation,
            `base64url(header).base64url(payload)[.base64url(signature)]`.

    Returns:
        {
          "header": dict (empty {} when the first segment is not a JSON object),
          "payload": dict or None,
          "signature": bytes or None,
          "alg": str or None (the header's algorithm, as claimed),
          "typ": str or None,
          "segments": int (1..3 actually present, 0 for an empty token),
          "errors": [str, ...] (what was wrong, in reading order),
          "weak_alg": bool (True for alg "none", for a missing/empty alg, and for
                            any HS* symmetric algorithm),
        }

    Nothing about the *content* raises. This helper gets pointed at log lines, proxy
    dumps and grep results where most strings are not JWTs at all, so anything that
    fails to decode is reported in `errors` with an empty `header` - the caller
    filters on `segments`/`errors` rather than catching exceptions in a loop. Only a
    non-string/None argument raises, because that is a misuse of the API rather than
    a token that did not parse.
    """
    if isinstance(token, (bytes, bytearray)):
        text = bytes(token).decode("ascii", "ignore").strip()
    elif isinstance(token, str):
        text = token.strip()
    else:
        raise ValueError("parse_jwt expects the compact serialisation as a string")

    out = {
        "header": {},
        "payload": None,
        "signature": None,
        "alg": None,
        "typ": None,
        "segments": 0,
        "errors": [],
        "weak_alg": False,
    }
    if not text:
        out["errors"].append("empty token")
        return out

    parts = text.split(".")
    if len(parts) > 3:
        out["errors"].append("token has %d segments (a JWS compact token has 3)"
                             % len(parts))
    if len(parts) == 1:
        out["errors"].append("no '.' separator found: not a compact JWS token")
    out["segments"] = min(len(parts), 3)

    for label, index in (("header", 0), ("payload", 1), ("signature", 2)):
        if index >= len(parts):
            continue
        segment = parts[index]
        if segment == "":
            if label != "signature":
                out["errors"].append("%s segment is empty" % label)
            continue
        try:
            raw = _b64url_decode(segment)
        except Exception as exc:
            out["errors"].append("%s segment does not decode: %s" % (label, exc))
            continue
        if label == "signature":
            out["signature"] = raw
            continue
        try:
            decoded = json.loads(raw.decode("utf-8"))
        except Exception as exc:
            out["errors"].append("%s segment is not JSON: %s" % (label, exc))
            continue
        if not isinstance(decoded, dict):
            out["errors"].append("%s segment is JSON but not an object" % label)
            continue
        out[label] = decoded

    if not out["header"]:
        # Not a JWT (or a header that never decoded). That is an ordinary answer for
        # this helper: report it in `errors` and hand back the empty document rather
        # than raising, so a caller can sweep a whole log file without try/except.
        if not out["errors"]:
            out["errors"].append("header segment is not a JSON object: not a JWT")
        return out

    alg = out["header"].get("alg")
    if isinstance(alg, str):
        out["alg"] = alg
        upper = alg.upper()
        out["weak_alg"] = upper == "NONE" or upper.startswith("HS")
    else:
        if alg is not None:
            out["errors"].append("header 'alg' is not a string")
        out["weak_alg"] = True
        out["errors"].append("header carries no usable 'alg'")

    typ = out["header"].get("typ")
    if isinstance(typ, str):
        out["typ"] = typ
    return out


