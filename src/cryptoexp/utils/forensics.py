# ------------------------------------------------------------------ batch GCD

def batch_gcd(moduli, progress=None):
    """Find every pair of RSA moduli that share a prime factor, in near-linear time

    Why a tester needs it: a fleet-wide key audit ("we dumped every public key in
    the estate / every certificate the load balancer served / every SSH host key")
    is decided by this one question. Two moduli sharing a prime means both private
    keys are recoverable by a single gcd, and the root cause is almost always a
    weak or forked RNG at manufacturing time (Debian OpenSSL, embedded devices
    with no entropy at first boot, a VM image cloned with its seed). The naive
    answer is the O(n^2) double loop, which for the 30,000-modulus dumps a
    researcher actually collects is ~450 million big-integer gcds - hours. The
    product/remainder tree below makes it practical: build the product of all
    moduli, propagate remainders down so that vertex i receives the product of
    every *other* modulus, then one gcd per modulus exposes each shared factor.
    Every reported factor is verified by division before it is returned, so the
    result is exact - there are no probabilistic "candidates" here.

    Complexity (big-integer operations, taking the moduli as n numbers of L bits):
        build the product tree   O(n * L) bit operations per level, O(log n) levels
        one root remainder       O(M(nL) * log(nL)) for a single nL-bit value
        remainder tree + gcds    ~2n modular reductions and n gcds, same order
        overall quasi-linear     ~O(n * L^2) bit operations (the gcd-avoidance
                                 result of Bernstein), i.e. n log^2 n word
                                 operations, versus O(n^2) for the naive loop.
    Space is the two trees: O(n * L) bits (~2x the root product), so a 40,000-key
    audit at 2048 bits stays in the low tens of MB.

    Args:
        moduli: iterable of positive ints (bytes are accepted and read big-endian).
            Values <= 1 are not keys and are skipped; their indices are reported
            in `skipped`, not silently dropped.
        progress: optional callable(status: str) invoked at the phase boundaries
            (it is an observability hook, not a status line the library prints).

    Returns:
        {
          "pairs":  [{"i": int, "j": int, "factor": int}, ...] sorted by (i, j),
                    one entry per unordered index pair sharing a factor;
          "checked": int - how many moduli took part,
          "groups": {factor: [indices, ...]} - every index that shares that factor,
          "skipped": [index, ...] - entries that were <= 1 or unparsable,
          "rejected": [{"factor", "indices"}, ...] - candidates that failed the
                      division check (always empty unless the tree math is wrong),
          "note": str - "" when nothing was found, otherwise what was found.
        }

    `groups` maps one integer factor to the sorted list of indices that share it, so
    it serialises straight to JSON (the keys become strings there). The factor is
    canonical: a bucket's key is the gcd of its members, so the same finding is not
    also reported under a composite multiple of it.
    """
    raw = list(moduli)
    ns = []
    skip = []
    for idx, value in enumerate(raw):
        if isinstance(value, (bytes, bytearray)):
            value = R.bytes_to_long(value)
        try:
            n = int(value)
        except (TypeError, ValueError):
            skip.append(idx)
            continue
        if n <= 1:
            skip.append(idx)
            continue
        ns.append((idx, n))

    if progress:
        progress("batch_gcd: %d usable moduli, building the product tree" % len(ns))

    out = {"pairs": [], "checked": len(ns), "groups": {}, "duplicates": {},
           "skipped": skip, "note": ""}
    if len(ns) < 2:
        out["note"] = "fewer than two usable moduli: nothing to compare"
        return out

    indices = [i for i, _ in ns]
    values = [n for _, n in ns]
    value_of = dict(zip(indices, values))

    # Duplicate moduli are their own finding: two "different" keys that are the same
    # key means one key pair was handed out twice. Reported separately because a
    # shared modulus is not a shared prime - gcd(n, n) = n, which would otherwise
    # surface as a "factor" equal to the modulus itself and mislead the caller.
    by_value = {}
    for idx, n in zip(indices, values):
        by_value.setdefault(n, []).append(idx)
    duplicates = {n: sorted(idxs) for n, idxs in by_value.items() if len(idxs) > 1}
    out = {"pairs": [], "checked": len(ns), "groups": {}, "duplicates": duplicates,
           "skipped": skip, "note": ""}
    if duplicates:
        out["note"] = "%d duplicate modulus(es) found" % len(duplicates)
    if len(ns) < 2:
        out["note"] = "fewer than two usable moduli: nothing to compare"
        return out

    # Product tree, root first; see `_product_tree` and `_remainder_tree` for why the
    # shape is root-first and why the descent squares each node value.
    levels = _product_tree(values)

    if progress:
        progress("batch_gcd: remainder tree")

    cur = _remainder_tree(levels)
    if progress:
        progress("batch_gcd: %d gcd tests" % len(values))

    buckets = {}
    for pos, idx in enumerate(indices):
        # cur[pos] is the product of every other modulus, reduced modulo this one, so
        # gcd > 1 means this modulus shares a factor with at least one other.
        g = A.gcd(values[pos], cur[pos])
        if g > 1:
            buckets.setdefault(g, set()).add(idx)

    # A factor can show up under several keys (the minimal gcd of a subset and,
    # separately, the full modulus of a duplicate). Merge keys that are not
    # coprime, then each bucket becomes exactly one canonical factor.
    keys = sorted(buckets)
    merged = []
    for key in keys:
        members = buckets[key]
        for entry in merged:
            if A.gcd(entry[0], key) > 1:
                entry[0] = A.gcd(entry[0], key)
                entry[1] |= members
                break
        else:
            merged.append([key, set(members)])

    groups = {}
    pairs = []
    rejected = []
    for factor, members in merged:
        if len(members) < 2:
            continue
        ordered = sorted(members)
        # Confirm by division before reporting. The remainder tree makes this true by
        # construction, so a failure here would mean the tree math is wrong: it is a
        # cheap, independent check that "we computed it" is really "it divides", and it
        # keeps a broken construction from ever reaching a report as a finding.
        if any(value_of[pos] % factor for pos in ordered):
            rejected.append({"factor": factor, "indices": ordered})
            continue
        groups[factor] = ordered
        for ai in range(len(ordered)):
            for bi in range(ai + 1, len(ordered)):
                pairs.append({"i": ordered[ai], "j": ordered[bi], "factor": factor})
    pairs.sort(key=lambda p: (p["i"], p["j"]))

    out["pairs"] = pairs
    out["groups"] = groups
    out["rejected"] = rejected
    if pairs:
        out["note"] = ("%d shared-factor pair(s) among %d moduli; %d distinct factor(s)"
                       % (len(pairs), len(ns), len(groups)))
    else:
        out["note"] = "no shared factors among %d moduli" % len(ns)
    if rejected:
        out["note"] += ("; %d candidate factor(s) failed the division check and were "
                        "not reported" % len(rejected))
    if progress:
        progress("batch_gcd: done, %d pair(s)" % len(pairs))
    return out


def _product_tree(values):
    """level[0] = the root product of all values, level[-1] = the values themselves

    Written root-first so the remainder descent below can read it straight down. A
    level with an odd count carries its last element up unchanged to the level above:
    that node has no partner to multiply with, and carrying it (rather than padding
    with a 1) keeps every leaf's ancestry honest about which moduli it covers.
    """
    levels = [list(values)]
    while len(levels[0]) > 1:
        top = levels[0]
        prev = [top[k] * top[k + 1] for k in range(0, len(top) - 1, 2)]
        if len(top) % 2:
            prev.append(top[-1])
        levels.insert(0, prev)
    return levels


def _remainder_tree(levels):
    """Descend the product tree -> for each modulus, the product of all the others mod it

    The step that makes a fleet-wide gcd audit practical. `levels[0]` is the whole
    product P (the root), `levels[k]` the nodes k steps below it, and `levels[-1]`
    the moduli themselves. The descent is the classical identity

        R(level)[i] = R(level - 1)[i // 2] mod value(level)[i]^2

    with the root starting at R = P. Squaring the node value is what makes the answer
    exact rather than merely "shares something": because n_i divides P, we have
    P == n_i * (P / n_i), so

        P mod n_i^2 == n_i * ((P / n_i) mod n_i)

    and dividing the leaf result by n_i leaves exactly the product of every *other*
    modulus, reduced modulo n_i - the number whose gcd with n_i is non-trivial
    precisely when n_i shares a factor with another modulus. (Reducing modulo n_i
    instead would send every non-shared modulus to 0 and report the whole fleet as
    weak.)

    The index map `i // 2` is uniform because the tree carries an odd leftover element
    up to the level above, which means the last child of a level and the last element
    of its parent are the same value - so the usual heap-style parent of child i is
    correct for every shape.

    Iterative, one array per level: a 100,000-modulus audit is 17 levels deep and
    never recurses. Cost is one squaring, one reduction and one division per node,
    i.e. O(n) big-integer operations - the same order as building the product tree
    itself, against O(n^2) for the naive double loop.

    Returns a list of `(P / n_i) mod n_i` values aligned with levels[-1] (the moduli,
    in order).
    """
    leaves = levels[-1]
    rem = [levels[0][0]]
    for level in range(1, len(levels)):
        values = levels[level]
        top = rem
        rem = [0] * len(values)
        for pos, value in enumerate(values):
            parent = top[pos // 2]
            if value > 1:
                rem[pos] = parent % (value * value)
            else:
                rem[pos] = 0
    return [rem[pos] // leaves[pos] if leaves[pos] > 1 else 0
            for pos in range(len(leaves))]

def common_factor_pairs(moduli):
    """[(i, j, factor), ...] from `batch_gcd` - the shape a report table wants

    A convenience wrapper only: identical computation, identical verification, just
    unpacked into tuples sorted by (i, j) so the caller can iterate straight into
    "host i and host j share prime p" without dictionary indexing.
    """
    res = batch_gcd(moduli)
    return [(p["i"], p["j"], p["factor"]) for p in res["pairs"]]


