def _severity_rank(severity):
    try:
        return _SEVERITY_ORDER.index(severity)
    except ValueError:
        return len(_SEVERITY_ORDER)


def _perfect_power(n):
    """Smallest exact power n = m^k (k >= 2) as (m, k), else None

    A cheap necessary condition first: if n is an exact k-th power then it is a
    k-th power modulo any small prime, so a modular filter rejects almost every
    exponent before the expensive integer root is attempted. Only the exponents
    that survive are handed to `algebra.iroot`, which keeps a 4096-bit modulus to
    a handful of Newton iterations.
    """
    if n < 4:
        return None
    for k in range(2, n.bit_length() + 1):
        if all(pow(n % p, (p - 1) // math.gcd(k, p - 1), p) in (0, 1)
               for p in (3, 5, 7, 11, 13)):
            root, exact = A.iroot(n, k)
            if exact and root > 1:
                return root, k
    return None


def _fermat_probe(n, budget):
    """Fermat factorisation bounded by `budget` rounds -> dict with the outcome

    Runs the whole budget and reports whether it succeeded, so "not close enough"
    and "gave up" can be told apart in the finding text. Only reached for odd,
    non-square, non-perfect-power n (Fermat on such input either returns p == 1 or
    terminates early, which is why the caller screens first).
    """
    if n % 2 == 0:
        return None
    a = math.isqrt(n)
    if a * a < n:
        a += 1
    for _ in range(budget):
        b2 = a * a - n
        b = A.perfect_square(b2)
        if b is not None:
            p, q = a - b, a + b
            if p > 1 and p * q == n:
                return p, q
        a += 1
    return None


def audit_rsa_key(n, e=None, extra_moduli=None, effort="normal"):
    """Audit one RSA modulus (optionally against a fleet) and report what is weak

    Why a tester needs it: "we found a 512-bit key on the VPN gateway" and "this
    appliance's keys share a prime with three other appliances" are report lines,
    and each of them is one of a handful of mechanical checks. This function runs
    them and hands back findings with a severity, so the same call works for a
    single certificate picked up during recon and for a batch of moduli from an
    inventory. It is honest about cost: `effort` selects how much work is spent on
    the search-based checks and any check that could not run says so in `checked`
    with the reason instead of quietly disappearing.

    Checks, in the order they are reported (finding id, severity in parentheses):
        modulus           n even, so 2 divides it (n_even, critical); n below
                          512/1024/2048 bits (n_bits_tiny critical /
                          n_bits_small high / n_bits_under_2048 medium)
        exponent          e == 1 leaks every plaintext (e_one, critical); e even is
                          not a valid public exponent (e_even, high); e < 3 is
                          invalid (e_invalid, high); e <= 17 means missing padding is
                          exploitable (small_exponent, info)
        perfect power     n == m^k (perfect_power, critical - trivially factorable)
        Fermat            p and q suspiciously close (fermat_close_primes, critical)
        Wiener            d below n^0.25/3, recoverable by continued fractions
                          (wiener, critical)
        smooth p-1        a factor p with p-1 smooth enough for Pollard p-1 in the
                          budget (p_minus_1_smooth, high)
        shared factor     n shares a prime with extra_moduli (shared_factor, critical)

    Args:
        n: the modulus (int, or bytes read big-endian).
        e: the public exponent when it is known (from the certificate/key). Not
            required - the exponent checks are then reported as not run.
        extra_moduli: other moduli from the same estate/fleet. A shared factor is
            the highest-value finding in this audit, so pass the whole inventory
            (or at least the siblings from the same appliance family) if you have
            it.
        effort: "quick" | "normal" | "deep". quick skips the p-1 search and uses a
            short Fermat budget; normal is the balanced default; deep spends far
            more time on Fermat and p-1. In BOTH non-quick tiers the failures are
            reported as bounded ("nothing within N iterations"), never as a claim
            that the key is safe.

    Returns:
        {
          "n_bits": int,
          "e": int or None,
          "findings": [{"id", "severity", "detail"}, ...] worst finding first,
          "checked": [{"check", "ok", "detail"}, ...] - one entry per check, `ok`
                     False meaning "could not run", with the reason in `detail`.
        }
    """
    if isinstance(n, (bytes, bytearray)):
        n = R.bytes_to_long(n)
    try:
        n = int(n)
    except (TypeError, ValueError):
        raise ValueError("audit_rsa_key: n must be an integer or bytes")
    if n <= 1:
        raise ValueError("audit_rsa_key: n must be > 1")
    if e is not None:
        try:
            e = int(e)
        except (TypeError, ValueError):
            raise ValueError("audit_rsa_key: e must be an integer")
    if effort not in ("quick", "normal", "deep"):
        raise ValueError("effort must be 'quick', 'normal' or 'deep'")

    if effort == "quick":
        pm1_bound, fermat_budget, deep = 0, 100000, False
    elif effort == "deep":
        pm1_bound, fermat_budget, deep = 50000, 1000000, True
    else:
        pm1_bound, fermat_budget, deep = 20000, 300000, False

    n_bits = n.bit_length()
    findings = []
    checked = []

    def note(check, ok, detail):
        checked.append({"check": check, "ok": bool(ok), "detail": detail})

    def find(fid, severity, detail):
        findings.append({"id": fid, "severity": severity, "detail": detail})

    note("modulus", True, "n is %d bits" % n_bits)
    if n_bits < 2048:
        # The ids carry the word "bits" so a report reader (or a grep over a JSON
        # finding list) can group every size problem together, whatever the threshold.
        # Only a sub-256-bit modulus is called critical: at that size factoring is a
        # coffee break, whereas 512/1024-bit keys are weak (high) rather than already
        # broken, and a report that cries critical at 511 bits would drown the real
        # "this key shares a prime with the router next door" finding next to it.
        if n_bits < 256:
            find("n_bits_tiny", "critical",
                 "n is only %d bits: factorable in a coffee break, not a usable key, "
                 "so treat the key material as public" % n_bits)
        elif n_bits < 512:
            find("n_bits_very_small", "high",
                 "n is %d bits: below 512 bits, which is factorable with modest "
                 "public tooling and should be rotated immediately" % n_bits)
        elif n_bits < 1024:
            find("n_bits_small", "high",
                 "n is %d bits: below every modern guideline (NIST SP 800-57), "
                 "reachable by modest hardware" % n_bits)
        else:
            find("n_bits_under_2048", "medium",
                 "n is %d bits: accepted by legacy TLS stacks but below the current "
                 "2048-bit floor" % n_bits)

    if e is None:
        note("exponent", False, "no e supplied: every exponent check was skipped")
    else:
        note("exponent", True, "e = %d" % e)
        if e == 1:
            find("e_one", "critical",
                 "e == 1: encryption is the identity, every ciphertext is the plaintext")
        elif e % 2 == 0:
            find("e_even", "high",
                 "e == %d is even: the map is not a bijection mod n, so decryption "
                 "is ill-defined and no standard implementation will accept it" % e)
        elif e < 3:
            find("e_invalid", "high", "e == %d is not a valid public exponent" % e)
        elif e <= 17:
            find("small_exponent", "info",
                 "e == %d is small: harmless with a correct padding scheme, but any "
                 "unpadded or partially padded use becomes a small-exponent attack "
                 "(integer root / Hasad broadcast)" % e)

    if n % 2 == 0:
        find("n_even", "critical",
             "n is even: 2 divides n, so the modulus is factored already")
        note("perfect_power", False, "skipped: n is even, the factor is known")
        note("fermat", False, "skipped: n is even, the factor is known")
        note("wiener", False, "skipped: n is even, the factor is known")
        note("p_minus_1", False, "skipped: n is even, the factor is known")
    else:
        power = _perfect_power(n)
        if power is None:
            note("perfect_power", True, "n is not an exact power m^k (k >= 2)")
        else:
            base, expo = power
            factor = pow(base, expo - 1)
            if 1 < factor < n:
                find("perfect_power", "critical",
                     "n = m^%d with m = %d: factors are p = m and q = m^%d"
                     % (expo, base, expo - 1))
            else:
                find("perfect_power", "info",
                     "n is an exact %d-th power of m = %d (m does not split into "
                     "two factors of the expected size)" % (expo, base))

        close = _fermat_probe(n, fermat_budget)
        if close:
            p, q = close
            # Report sizes, not the factors themselves: a report line has to stay
            # readable, and |p - q| is what makes Fermat cheap (it costs about
            # |p - q|^2 / (4*sqrt(n)) rounds).
            find("fermat_close_primes", "critical",
                 "p and q are %d-bit primes only %d bits apart (|p-q| has %d bits): "
                 "Fermat factorisation recovers them in %d rounds, which is a "
                 "mis-generated key rather than a size problem"
                 % (min(p, q).bit_length(), abs(p - q).bit_length(),
                    abs(p - q).bit_length(), (abs(p - q) ** 2) // (4 * A.isqrt(n)) + 1))
            note("fermat", True, "p and q are close enough for Fermat")
        else:
            note("fermat", True,
                 "no factorisation within %d Fermat iterations (bounded search, not "
                 "a proof that p and q are far apart)" % fermat_budget)

        if e is None or e <= 1:
            note("wiener", False,
                 "no usable e supplied, so the continued-fraction convergents of e/n "
                 "cannot be computed")
        else:
            hit = A.wiener_recover_d(e, n)
            if hit is None:
                note("wiener", True, "d does not meet the Wiener bound (d < n^0.25/3)")
            else:
                d, p, q = hit
                find("wiener", "critical",
                     "Wiener attack recovered d = %d (%d bits) with p = %d, q = %d"
                     % (d, d.bit_length(), p, q))
                note("wiener", True, "small d recovered from the convergents of e/n")

        if pm1_bound <= 0:
            note("p_minus_1", False,
                 "effort=quick skips the Pollard p-1 search; rerun with "
                 "effort='normal' or 'deep' to test p-1 smoothness")
        else:
            factor = M.pollard_pm1(n, bound=pm1_bound)
            if factor is None:
                note("p_minus_1", True,
                     "no factor p with p-1 smooth up to %d (bounded search)" % pm1_bound)
            else:
                find("p_minus_1_smooth", "high",
                     "Pollard p-1 found the factor %d: its p-1 is smooth up to %d"
                     % (factor, pm1_bound))
                note("p_minus_1", True, "p-1 smoothness confirmed, p = %d" % factor)

    if extra_moduli is None:
        note("shared_factor", False, "no extra_moduli supplied: nothing to compare with")
    else:
        others = []
        skip = 0
        for value in extra_moduli:
            if isinstance(value, (bytes, bytearray)):
                value = R.bytes_to_long(value)
            try:
                value = int(value)
            except (TypeError, ValueError):
                skip += 1
                continue
            if value > 1:
                others.append(value)
        if not others:
            note("shared_factor", False,
                 "extra_moduli carried no usable modulus (%d unparsable)" % skip)
        else:
            res = batch_gcd([n] + others, progress=None)
            hits = res["pairs"]
            if not hits:
                note("shared_factor", True,
                     "no shared prime with %d other modulus/moduli" % len(others))
            else:
                factors = sorted({p["factor"] for p in hits})
                find("shared_factor", "critical",
                     "shares a prime factor (%s) with %d other modulus/moduli: both "
                     "private keys are recoverable by gcd alone, which points at a "
                     "weak or forked RNG rather than at the key sizes"
                     % (", ".join(str(f) for f in factors[:4]), len(hits)))
                note("shared_factor", True,
                     "%d modulus/moduli share a factor with n" % len(hits))

    findings.sort(key=lambda f: _severity_rank(f["severity"]))
    return {"n_bits": n_bits, "e": e, "findings": findings, "checked": checked}


